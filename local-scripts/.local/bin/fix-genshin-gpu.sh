#!/bin/bash
# ============================================================
# fix-genshin-gpu.sh
# Sửa lỗi GPU:0 Error 0x0000c57d & Genshin không launch được
# qua TwintailLauncher trên Arch Linux + NVIDIA GTX 1650 (Optimus)
# ============================================================

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
BLUE='\033[0;34m'; CYAN='\033[0;36m'; NC='\033[0m'

print_header() { echo -e "\n${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"; echo -e "${CYAN}  $1${NC}"; echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"; }
ok()   { echo -e "${GREEN}  ✅ $1${NC}"; }
warn() { echo -e "${YELLOW}  ⚠️  $1${NC}"; }
err()  { echo -e "${RED}  ❌ $1${NC}"; }
info() { echo -e "     ${CYAN}$1${NC}"; }

# ─── Kiểm tra quyền root ────────────────────────────────────
if [ "$EUID" -ne 0 ]; then
    echo -e "${YELLOW}Script cần quyền root. Đang chạy lại với sudo...${NC}"
    exec sudo bash "$0" "$@"
    exit
fi

print_header "🔍 Phân tích hệ thống"

DRIVER_VER=$(cat /sys/module/nvidia/version 2>/dev/null || echo "N/A")
GPU_BUS=$(ls /sys/bus/pci/drivers/nvidia/ 2>/dev/null | grep "0000:" | head -1)
DPM=$(cat /proc/driver/nvidia/params 2>/dev/null | grep "DynamicPowerManagement" | awk '{print $2}')
ENVYCONTROL_MODE=$(envycontrol -q 2>&1 || echo "unknown")

echo -e "  Driver NVIDIA : ${CYAN}${DRIVER_VER}${NC}"
echo -e "  GPU Bus       : ${CYAN}${GPU_BUS}${NC}"
echo -e "  DPM hiện tại  : ${CYAN}${DPM}${NC} (3=Fine-Grained gây lỗi, cần 2)"
echo -e "  EnvyControl   : ${CYAN}${ENVYCONTROL_MODE}${NC}"

# ─── FIX 1: NVIDIA modprobe.d/nvidia.conf ───────────────────
print_header "🔧 Fix 1: NVIDIA modprobe parameters"

# Backup
cp /etc/modprobe.d/nvidia.conf /etc/modprobe.d/nvidia.conf.bak 2>/dev/null
cp /etc/modprobe.d/nvidia-suspend.conf /etc/modprobe.d/nvidia-suspend.conf.bak 2>/dev/null

# Viết nvidia.conf chuẩn cho Optimus hybrid
cat > /etc/modprobe.d/nvidia.conf << 'MODPROBE_CONF'
# Automatically generated by EnvyControl (patched for GPU stability)
# Fix: GPU_IS_LOST / error 0x0000c57d trên GTX 1650 Optimus

options nvidia-drm modeset=1
options nvidia NVreg_UsePageAttributeTable=1 NVreg_InitializeSystemMemoryAllocations=0

# QUAN TRỌNG: DPM=0x02 (Coarse-grained) thay vì 3 (Fine-grained)
# Fine-grained DPM trên laptop Optimus gây GPU bị "lost from bus"
# sau khi app cố dùng NVIDIA GPU (0x0000c57d = timeout waiting GPU progress)
options nvidia NVreg_DynamicPowerManagement=0x02

# Giữ VRAM khi suspend để tránh GPU_IS_LOST sau resume
options nvidia NVreg_PreserveVideoMemoryAllocations=1
options nvidia NVreg_UseKernelSuspendNotifiers=1
MODPROBE_CONF

ok "nvidia.conf đã được cập nhật"

cat > /etc/modprobe.d/nvidia-suspend.conf << 'SUSPEND_CONF'
# NVIDIA suspend/resume fix - prevent GPU_IS_LOST after system resume
options nvidia NVreg_PreserveVideoMemoryAllocations=1
options nvidia NVreg_UseKernelSuspendNotifiers=1
SUSPEND_CONF

ok "nvidia-suspend.conf đã được cập nhật"

# ─── FIX 2: Bật NVIDIA systemd suspend/resume services ──────
print_header "🔧 Fix 2: Bật NVIDIA systemd suspend/resume services"

for svc in nvidia-suspend nvidia-hibernate nvidia-resume; do
    if systemctl enable "$svc" 2>/dev/null; then
        ok "$svc enabled"
    else
        warn "$svc: không tìm thấy (bỏ qua)"
    fi
done

# ─── FIX 3: Desktop file TwintailLauncher tối ưu ────────────
print_header "🔧 Fix 3: Cập nhật desktop file TwintailLauncher"

DESKTOP_USER="/home/mr-thai/.local/share/applications/twintaillauncher.desktop"
DESKTOP_BACKUP="${DESKTOP_USER}.bak"

cp "$DESKTOP_USER" "$DESKTOP_BACKUP" 2>/dev/null && ok "Backup: $DESKTOP_BACKUP"

# Desktop file tối ưu với các env vars đúng để NVIDIA hoạt động
cat > "$DESKTOP_USER" << 'DESKTOP_EOF'
[Desktop Entry]
Categories=Game;
Comment=Your anime games, one launcher
Exec=env WINEFSYNC=1 WINEESYNC=1 DXVK_ASYNC=1 MESA_VK_DEVICE_SELECT="10de:1f91" DXVK_FILTER_DEVICE_NAME="NVIDIA" PROTON_USE_WINED3D=0 PROTON_NO_ESYNC=0 PROTON_NO_FSYNC=0 gamemoderun prime-run twintaillauncher
Icon=twintaillauncher
Name=TwintailLauncher
Terminal=false
Type=Application
Keywords=genshin;impact;honkai;star;rail;zenless;zone;zero;wuthering;waves;hsr;zzz;hi3;wuwa;gimi;srmi;zzmi;wwmi;himi;xxmi
DESKTOP_EOF

chown mr-thai:mr-thai "$DESKTOP_USER"
ok "Desktop file TwintailLauncher đã được cập nhật"

# ─── FIX 4: initramfs rebuild ────────────────────────────────
print_header "🔧 Fix 4: Rebuild initramfs (áp dụng modprobe changes)"

if command -v mkinitcpio &>/dev/null; then
    echo "  Đang rebuild initramfs..."
    mkinitcpio -P 2>&1 | tail -5
    ok "initramfs đã rebuild"
else
    warn "mkinitcpio không tìm thấy"
fi

# ─── FIX 5: Áp dụng ngay không cần reboot (best-effort) ────
print_header "🔧 Fix 5: Áp dụng ngay (không cần reboot)"

# Thử set DPM runtime nếu driver đang load
if [ -f /proc/driver/nvidia/params ]; then
    # Không thể thay đổi DPM khi module đang chạy - cần reboot
    warn "DPM cần reboot để có hiệu lực (modprobe parameter)"
else
    ok "NVIDIA module chưa load - changes sẽ có hiệu lực khi load"
fi

# Cập nhật desktop database
sudo -u mr-thai update-desktop-database /home/mr-thai/.local/share/applications/ 2>/dev/null && ok "Desktop database updated"

# ─── FIX 6: Script khởi động nhanh TwintailLauncher ────────
print_header "🔧 Fix 6: Tạo script launch Genshin an toàn"

cat > /home/mr-thai/.local/bin/launch-genshin.sh << 'LAUNCH_EOF'
#!/bin/bash
# Launch Genshin Impact qua TwintailLauncher với GPU tối ưu
# Đảm bảo NVIDIA GPU active trước khi launch

echo "🎮 Chuẩn bị khởi động Genshin Impact..."

# Wake up NVIDIA GPU nếu đang suspended
if [ -f /sys/bus/pci/devices/0000:01:00.0/power/control ]; then
    echo "on" | sudo tee /sys/bus/pci/devices/0000:01:00.0/power/control > /dev/null 2>&1
    sleep 1
fi

# Kiểm tra GPU status
GPU_STATUS=$(cat /sys/bus/pci/devices/0000:01:00.0/power/runtime_status 2>/dev/null)
echo "   GPU power status: $GPU_STATUS"

# Launch với env vars đầy đủ
exec env \
    WINEFSYNC=1 \
    WINEESYNC=1 \
    DXVK_ASYNC=1 \
    MESA_VK_DEVICE_SELECT="10de:1f91" \
    DXVK_FILTER_DEVICE_NAME="NVIDIA" \
    __NV_PRIME_RENDER_OFFLOAD=1 \
    __VK_LAYER_NV_optimus=NVIDIA_only \
    __GLX_VENDOR_LIBRARY_NAME=nvidia \
    gamemoderun \
    twintaillauncher
LAUNCH_EOF

chown mr-thai:mr-thai /home/mr-thai/.local/bin/launch-genshin.sh
chmod +x /home/mr-thai/.local/bin/launch-genshin.sh
ok "Script /home/mr-thai/.local/bin/launch-genshin.sh tạo xong"

# ─── TỔNG KẾT ───────────────────────────────────────────────
print_header "📋 Tóm tắt & Bước tiếp theo"

echo ""
echo -e "  ${GREEN}Các fix đã áp dụng:${NC}"
echo "  1. ✅ nvidia.conf: DPM=2 (Coarse) thay DPM=3 (Fine-Grained gây crash)"
echo "  2. ✅ nvidia-suspend.conf: PreserveVideoMemory + KernelSuspendNotifiers"
echo "  3. ✅ nvidia-suspend/hibernate/resume systemd services: enabled"
echo "  4. ✅ initramfs rebuilt"
echo "  5. ✅ Desktop file TwintailLauncher: env vars tối ưu"
echo "  6. ✅ Script launch-genshin.sh: wake GPU trước khi launch"
echo ""
echo -e "  ${YELLOW}⚡ CẦN REBOOT để các thay đổi modprobe có hiệu lực!${NC}"
echo ""
echo -e "  ${CYAN}Sau reboot, test bằng:${NC}"
echo "    1. TwintailLauncher từ app menu (đã fix desktop file)"
echo "    2. Hoặc chạy: launch-genshin.sh"
echo "    3. Kiểm tra DPM: cat /proc/driver/nvidia/params | grep DynamicPower"
echo "       → Phải hiện: DynamicPowerManagement: 2"
echo ""
echo -e "  ${CYAN}Nếu vẫn lỗi sau reboot:${NC}"
echo "    sudo envycontrol -s hybrid --rtd3 0   (tắt runtime D3 hoàn toàn)"
echo "    sudo mkinitcpio -P && reboot"
